#!/usr/bin/env bash
#
# Regenerates the data embedded in cli/exbloattv from the app's own sources, so the script never drifts from the app:
#   - the app catalog       app/src/main/assets/catalog.json
#   - the safety lists      app/src/main/java/dev/xpdt/exbloattv/safety/SafetyGuard.kt (NEVER and REMOTE_INPUT)
# The data goes between the ">>> generated" and "<<< generated" lines of cli/exbloattv, which stays a single file you
# can download and run on its own.
#
#   cli/gen-catalog.sh           rewrite the block
#   cli/gen-catalog.sh --check   exit 1 if the block is stale (run by cli/test.sh)

set -eu
here=$(cd "$(dirname "$0")" && pwd)
root=$(dirname "$here")
script=$here/exbloattv
catalog=$root/app/src/main/assets/catalog.json
guard=$root/app/src/main/java/dev/xpdt/exbloattv/safety/SafetyGuard.kt
tmp=$(mktemp -d "${TMPDIR:-/tmp}/exbloattv-gen.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

fail() {
	echo "gen-catalog: $*" >&2
	exit 2
}
[ -f "$catalog" ] || fail "missing $catalog"
[ -f "$guard" ] || fail "missing $guard"

# The script's own JSON parser flattens catalog.json to "entries.N.key<TAB>value" lines.
# shellcheck disable=SC1090
EXBLOATTV_LIB=1 . "$script"
json_flat <"$catalog" >"$tmp/flat" || fail "catalog.json is not valid JSON: $(head -n 1 "$tmp/flat")"

# One row per entry: pattern, category, name, description, defaultKeep, locked, musicApp (1/0). Fields as in
# catalog/Catalog.kt (CatalogEntry): description, locked and musicApp are optional.
LC_ALL=C awk -F'\t' -v OFS='\037' '
function bool(v, dflt, what) { if (v == "") return dflt; if (v == "true") return 1; if (v == "false") return 0; bad = bad " " what "=" v; return 0 }
$1 ~ /^entries\.[0-9]+\./ {
	split($1, p, "."); i = p[2] + 0; if (i + 1 > n) n = i + 1
	v[i, p[3]] = $2; has[i, p[3]] = 1
}
END {
	cats = " STREAMING MUSIC LIVE_TV FEATURES GOOGLE_EXTRAS MANUFACTURER ADS_TRACKING SIDELOAD_TOOLS OTHER SYSTEM LAUNCHER "
	for (i = 0; i < n; i++) {
		if (!has[i, "pattern"] || !has[i, "category"] || !has[i, "name"] || !has[i, "defaultKeep"]) { print "entry " i " is missing a required field" > "/dev/stderr"; exit 1 }
		if (index(cats, " " v[i, "category"] " ") == 0) { print "entry " i ": unknown category " v[i, "category"] > "/dev/stderr"; exit 1 }
		if (v[i, "pattern"] in seen) { print "duplicate pattern " v[i, "pattern"] > "/dev/stderr"; exit 1 }
		seen[v[i, "pattern"]] = 1
		print v[i, "pattern"], v[i, "category"], v[i, "name"], v[i, "description"], bool(v[i, "defaultKeep"], 0, "defaultKeep"), bool(v[i, "locked"], 0, "locked"), bool(v[i, "musicApp"], 0, "musicApp")
	}
	if (bad != "") { print "bad booleans:" bad > "/dev/stderr"; exit 1 }
	if (n == 0) { print "no entries" > "/dev/stderr"; exit 1 }
}' "$tmp/flat" >"$tmp/catalog.tsv" || fail "catalog.json doesn't have the expected shape"

expected=$(grep -c '"pattern"' "$catalog")
[ "$(wc -l <"$tmp/catalog.tsv" | tr -d ' ')" = "$expected" ] || fail "parsed $(wc -l <"$tmp/catalog.tsv") entries, catalog.json has $expected"

# String literals of `val NEVER: List<String> = listOf(` ... `)` and of REMOTE_INPUT, in order.
kotlin_list() {
	awk -v start="$1" '
	index($0, start) { on = 1; next }
	on && /^[ \t]*\)/ { exit }
	on { sub(/\/\/.*/, ""); while (match($0, /"[^"]*"/)) { print substr($0, RSTART + 1, RLENGTH - 2); $0 = substr($0, RSTART + RLENGTH) } }' "$guard"
}
kotlin_list 'val NEVER: List<String> = listOf(' >"$tmp/never"
kotlin_list 'val REMOTE_INPUT: List<String> = listOf(' >"$tmp/remote"
grep -qx android "$tmp/never" || fail "couldn't read SafetyGuard.NEVER"
[ -s "$tmp/remote" ] || fail "couldn't read SafetyGuard.REMOTE_INPUT"
if grep -v '^[A-Za-z0-9_.*]*$' "$tmp/never" "$tmp/remote"; then fail "a SafetyGuard pattern uses characters other than letters, digits, _ . and *"; fi

{
	echo "# >>> generated by cli/gen-catalog.sh from app/src/main/assets/catalog.json and SafetyGuard.kt. Do not edit by hand."
	printf '# %s catalog entries: pattern, category, name, description, defaultKeep, locked, musicApp (\\037-separated).\n' "$(wc -l <"$tmp/catalog.tsv" | tr -d ' ')"
	echo "catalog_tsv() {"
	echo "	cat <<'EOF_CATALOG'"
	cat "$tmp/catalog.tsv"
	echo "EOF_CATALOG"
	echo "}"
	echo "# SafetyGuard.NEVER: never switched off or removed. \`*\` matches any run of characters."
	echo "never_disable() {"
	echo "	cat <<'EOF_NEVER'"
	cat "$tmp/never"
	echo "EOF_NEVER"
	echo "}"
	echo "# SafetyGuard.REMOTE_INPUT: remote, keyboard and pairing packages; protected and never shown."
	echo "remote_input() {"
	echo "	cat <<'EOF_REMOTE'"
	cat "$tmp/remote"
	echo "EOF_REMOTE"
	echo "}"
	echo "# <<< generated"
} >"$tmp/block"

# Replace everything from the ">>> generated" line to the "<<< generated" line.
awk -v blockfile="$tmp/block" '
/^# >>> generated/ { while ((getline line < blockfile) > 0) print line; skip = 1; found++; next }
/^# <<< generated/ { skip = 0; next }
!skip { print }
END { if (found != 1) exit 3 }' "$script" >"$tmp/new" || fail "couldn't find exactly one generated block in $script"

if [ "${1:-}" = --check ]; then
	if cmp -s "$script" "$tmp/new"; then
		echo "gen-catalog: up to date ($expected catalog entries, $(wc -l <"$tmp/never" | tr -d ' ') never-disable, $(wc -l <"$tmp/remote" | tr -d ' ') remote-input patterns)"
		exit 0
	fi
	echo "gen-catalog: cli/exbloattv is stale; run cli/gen-catalog.sh" >&2
	diff "$script" "$tmp/new" | head -n 20 >&2 || true
	exit 1
fi
cat "$tmp/new" >"$script" # keep the file's mode
echo "gen-catalog: wrote $expected catalog entries and the SafetyGuard lists into cli/exbloattv"
